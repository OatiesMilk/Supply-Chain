import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import multer from 'multer';
import type { NextFunction, Request, Response } from 'express';
import { discardUpload, withFileInMemory } from './podStorage';

/**
 * Upload quarantine for TASS -> Logistics dispatch attachments (Client Slips PDF
 * + DRRMMDDYY.xlsx). Files land on a private temp directory that is isolated from
 * POD and signature storage, are verified by content (never by declared name or
 * type), are emailed, and are always deleted. They are never persisted.
 */
export const MAX_DISPATCH_FILE_BYTES = 5 * 1024 * 1024;
export const MAX_DISPATCH_TOTAL_BYTES = 8 * 1024 * 1024;
export const DISPATCH_FILE_TOO_LARGE_ERROR = 'Each dispatch attachment must be 5 MB or smaller.';
export const DISPATCH_TOTAL_TOO_LARGE_ERROR = 'Dispatch attachments must total 8 MB or less.';
export const INVALID_DISPATCH_PDF = 'The Client Slips attachment must be a valid PDF document.';
export const INVALID_DISPATCH_XLSX = 'The Daily Route Slip attachment must be a valid .xlsx workbook.';
export const MACRO_DISPATCH_XLSX = 'Macro-enabled workbooks cannot be dispatched.';

export function dispatchQuarantineDir(env: NodeJS.ProcessEnv = process.env): string {
  return path.resolve(env.DISPATCH_TEMP_DIR || path.join(os.tmpdir(), 'mg-dispatch-uploads'));
}
const quarantineDir = dispatchQuarantineDir();

export class DispatchFileError extends Error {
  constructor(public status: number, message: string) { super(message); this.name = 'DispatchFileError'; }
}

export type DispatchFiles = { client_slips?: Express.Multer.File[]; route_slip?: Express.Multer.File[] };

export const dispatchUpload = multer({
  storage: multer.diskStorage({
    destination: (_req, _file, callback) => {
      fs.mkdir(quarantineDir, { recursive: true, mode: 0o700 }, error => callback(error, quarantineDir));
    },
    // Client file names are ignored: the quarantine name is random and the
    // emailed attachment names are generated by the server.
    filename: (_req, _file, callback) => callback(null, crypto.randomUUID()),
  }),
  limits: { fileSize: MAX_DISPATCH_FILE_BYTES, files: 2, fields: 16 },
});

function uploadedPaths(req: Request): string[] {
  const files = req.files as DispatchFiles | Express.Multer.File[] | undefined;
  if (!files) return [];
  const list = Array.isArray(files) ? files : [...(files.client_slips ?? []), ...(files.route_slip ?? [])];
  return list.map(file => file.path).filter(Boolean);
}

/** Dispatch-specific upload errors (5 MB per file) without touching the POD 10 MB handler. */
export function handleDispatchUpload(req: Request, res: Response, next: NextFunction) {
  dispatchUpload.fields([{ name: 'client_slips', maxCount: 1 }, { name: 'route_slip', maxCount: 1 }])(req, res, (error: unknown) => {
    if (!error) return next();
    void discardDispatchFiles(uploadedPaths(req));
    const err = error as Error & { code?: string };
    if (err.name === 'MulterError' && err.code === 'LIMIT_FILE_SIZE') return res.status(413).json({ error: DISPATCH_FILE_TOO_LARGE_ERROR });
    if (err.name === 'MulterError') return res.status(400).json({ error: 'Upload one "client_slips" PDF and one "route_slip" workbook.' });
    next(error);
  });
}

export function dispatchUploadPaths(req: Request): string[] { return uploadedPaths(req); }

export async function discardDispatchFiles(paths: readonly (string | undefined)[]): Promise<void> {
  await Promise.all(paths.map(filePath => discardUpload(filePath)));
}

async function readQuarantined(filePath: string, invalid: string): Promise<Buffer> {
  const resolved = path.resolve(filePath);
  const stats = await fs.promises.stat(resolved).catch(() => null);
  if (!stats?.isFile() || stats.size <= 0) throw new DispatchFileError(400, invalid);
  if (stats.size > MAX_DISPATCH_FILE_BYTES) throw new DispatchFileError(413, DISPATCH_FILE_TOO_LARGE_ERROR);
  return fs.promises.readFile(resolved);
}

/** `%PDF-` header at byte 0 and an `%%EOF` marker within the final 1024 bytes. */
export function isDispatchPdf(bytes: Buffer): boolean {
  if (bytes.length < 16 || bytes.subarray(0, 5).toString('latin1') !== '%PDF-') return false;
  return bytes.subarray(Math.max(0, bytes.length - 1024)).toString('latin1').includes('%%EOF');
}

/** Central-directory entry names of a ZIP archive, or null when the archive is malformed. */
export function zipEntryNames(bytes: Buffer): string[] | null {
  if (bytes.length < 22 || bytes.readUInt32LE(0) !== 0x04034b50) return null;
  // End of central directory: fixed 22 bytes plus an optional comment of up to 65535 bytes.
  const floor = Math.max(0, bytes.length - 22 - 0xffff);
  let eocd = -1;
  for (let offset = bytes.length - 22; offset >= floor; offset--) {
    if (bytes.readUInt32LE(offset) === 0x06054b50) { eocd = offset; break; }
  }
  if (eocd < 0) return null;
  const entries = bytes.readUInt16LE(eocd + 10);
  const size = bytes.readUInt32LE(eocd + 12);
  const start = bytes.readUInt32LE(eocd + 16);
  if (start + size > eocd) return null;
  const names: string[] = [];
  let offset = start;
  for (let index = 0; index < entries; index++) {
    if (offset + 46 > eocd || bytes.readUInt32LE(offset) !== 0x02014b50) return null;
    const nameLength = bytes.readUInt16LE(offset + 28);
    const extraLength = bytes.readUInt16LE(offset + 30);
    const commentLength = bytes.readUInt16LE(offset + 32);
    const end = offset + 46 + nameLength;
    if (end > eocd) return null;
    names.push(bytes.subarray(offset + 46, end).toString('utf8'));
    offset = end + extraLength + commentLength;
  }
  return names;
}

/** OOXML workbook: ZIP with `[Content_Types].xml` and `xl/workbook.xml`, and no VBA project. */
export function dispatchXlsxError(bytes: Buffer): string | null {
  const names = zipEntryNames(bytes);
  if (!names) return INVALID_DISPATCH_XLSX;
  const lower = names.map(name => name.toLowerCase());
  if (lower.some(name => name.endsWith('vbaproject.bin'))) return MACRO_DISPATCH_XLSX;
  if (!names.includes('[Content_Types].xml') || !names.includes('xl/workbook.xml')) return INVALID_DISPATCH_XLSX;
  return null;
}

export async function inspectDispatchPdf(filePath: string): Promise<Buffer> {
  return withFileInMemory(async () => {
    const bytes = await readQuarantined(filePath, INVALID_DISPATCH_PDF);
    if (!isDispatchPdf(bytes)) throw new DispatchFileError(400, INVALID_DISPATCH_PDF);
    return bytes;
  });
}

export async function inspectDispatchXlsx(filePath: string): Promise<Buffer> {
  return withFileInMemory(async () => {
    const bytes = await readQuarantined(filePath, INVALID_DISPATCH_XLSX);
    const error = dispatchXlsxError(bytes);
    if (error) throw new DispatchFileError(400, error);
    return bytes;
  });
}

// Files left behind by a crash or restart mid-dispatch. Run at startup.
export async function removeStaleDispatchUploads(olderThanMs = 60 * 60 * 1000): Promise<number> {
  const names = await fs.promises.readdir(quarantineDir).catch(() => [] as string[]);
  let removed = 0;
  for (const name of names) {
    const filePath = path.join(quarantineDir, name);
    const stats = await fs.promises.stat(filePath).catch(() => null);
    if (stats?.isFile() && Date.now() - stats.mtimeMs > olderThanMs) {
      await discardUpload(filePath);
      removed++;
    }
  }
  return removed;
}
