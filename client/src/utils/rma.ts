/**
 * The six TASS slip categories. Mirrors server/src/services/rmaRules.ts; the
 * server allocates the <PREFIX><MMDDYY>-<NN> slip reference on save.
 */
export const RMA_CATEGORIES = [
  'Pull Out Slip',
  'Return to Customer Slip',
  'Return to Supplier Slip',
  'Advance Replacement Slip',
  'Receiving Slip',
  'Transfer Out Slip',
] as const;

export type RmaCategory = (typeof RMA_CATEGORIES)[number];
export type RmaSlipPrefix = 'POS' | 'RTC' | 'RTS' | 'ARD' | 'RR' | 'TXO';

export const RMA_CATEGORY_META: Readonly<Record<RmaCategory, { prefix: RmaSlipPrefix; label: RmaCategory; slipTitle: string }>> = {
  'Pull Out Slip': { prefix: 'POS', label: 'Pull Out Slip', slipTitle: 'PULL OUT SLIP' },
  'Return to Customer Slip': { prefix: 'RTC', label: 'Return to Customer Slip', slipTitle: 'RETURN TO CUSTOMER SLIP' },
  'Return to Supplier Slip': { prefix: 'RTS', label: 'Return to Supplier Slip', slipTitle: 'RETURN TO SUPPLIER SLIP' },
  'Advance Replacement Slip': { prefix: 'ARD', label: 'Advance Replacement Slip', slipTitle: 'ADVANCE REPLACEMENT SLIP' },
  'Receiving Slip': { prefix: 'RR', label: 'Receiving Slip', slipTitle: 'RECEIVING SLIP' },
  'Transfer Out Slip': { prefix: 'TXO', label: 'Transfer Out Slip', slipTitle: 'TRANSFER OUT SLIP' },
};

export const RMA_CATEGORY_PREFIX: Readonly<Record<RmaCategory, RmaSlipPrefix>> = Object.fromEntries(
  RMA_CATEGORIES.map(category => [category, RMA_CATEGORY_META[category].prefix]),
) as Record<RmaCategory, RmaSlipPrefix>;

export const TRANSFER_OUT_CATEGORY: RmaCategory = 'Transfer Out Slip';
export const RECEIVING_SLIP_CATEGORY: RmaCategory = 'Receiving Slip';
export const INTERNAL_TRANSFER_LABEL = 'Non-RMA Internal Transfer';

const LEGACY_ALIASES: Readonly<Record<string, RmaCategory>> = {
  'Pull-Out Slip': 'Pull Out Slip', 'Pull out': 'Pull Out Slip', POS: 'Pull Out Slip',
  'Return to Customer': 'Return to Customer Slip', RTC: 'Return to Customer Slip',
  'Return to Supplier': 'Return to Supplier Slip', 'Return to suppliers': 'Return to Supplier Slip', RTS: 'Return to Supplier Slip',
  'Advance Replacement Demo': 'Advance Replacement Slip', 'Advance Replacement': 'Advance Replacement Slip', ARD: 'Advance Replacement Slip',
  'Receiving Report': 'Receiving Slip', RR: 'Receiving Slip',
  TXO: 'Transfer Out Slip',
};

/** Canonical slip category for a stored label (legacy aliases included), or null for retired/unknown labels. */
export function canonicalRmaCategory(value: string | null | undefined): RmaCategory | null {
  if (typeof value !== 'string') return null;
  const trimmed = value.trim();
  const mapped = LEGACY_ALIASES[trimmed] ?? trimmed;
  return (RMA_CATEGORIES as readonly string[]).includes(mapped) ? mapped as RmaCategory : null;
}

export function isCanonicalRmaCategory(value: string | null | undefined): value is RmaCategory {
  return typeof value === 'string' && (RMA_CATEGORIES as readonly string[]).includes(value);
}

export function isTransferOutCategory(value: string | null | undefined): boolean {
  return canonicalRmaCategory(value) === TRANSFER_OUT_CATEGORY;
}

export function rmaCategoryPrefix(value: string | null | undefined): RmaSlipPrefix | null {
  const category = canonicalRmaCategory(value);
  return category ? RMA_CATEGORY_PREFIX[category] : null;
}

/** Printed slip title; RMA records without a canonical category keep the generic title. */
export function rmaSlipTitle(value: string | null | undefined): string {
  const category = canonicalRmaCategory(value);
  return category ? RMA_CATEGORY_META[category].slipTitle : 'RMA SLIP';
}

/** Dropdown label, e.g. "Pull Out Slip (POS)". */
export function formatRmaCategoryOption(category: RmaCategory): string {
  return `${category} (${RMA_CATEGORY_PREFIX[category]})`;
}

const manilaDate = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Manila', year: 'numeric', month: '2-digit', day: '2-digit' });

/** Display-only placeholder of the reference the server will allocate on save, e.g. POS112426-NN. */
export function previewRmaReference(value: string | null | undefined, now = new Date()): string | null {
  const prefix = rmaCategoryPrefix(value);
  if (!prefix) return null;
  const [year, month, day] = manilaDate.format(now).split('-');
  return `${prefix}${month}${day}${year.slice(-2)}-NN`;
}

/** Auto Fill picks a category only; the slip reference is always generated by the server. */
export function autoFillRmaFields(_currentReference: string, categoryIndex: number) {
  const index = Number.isFinite(categoryIndex) ? Math.max(0, Math.min(RMA_CATEGORIES.length - 1, Math.floor(categoryIndex))) : 0;
  return { reference: '', rma_type: RMA_CATEGORIES[index] };
}
