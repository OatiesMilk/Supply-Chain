/**
 * DEF-019 — Monthly Driver Report CSV shape verification
 *
 * Product Decision (recorded 2026-10-20, owner: @roelandremagbitang):
 *   The Monthly Driver Report CSV is AGGREGATE-ONLY by product design.
 *   It emits performance totals, time-bucket breakdowns, area coverage, vehicle
 *   plate totals, and driver remarks — one summary row per driver, not one row
 *   per delivery. This is the intended output shape, not an unpatched defect.
 *
 *   Per-delivery detail is NOT required for the monthly driver report.
 *   If individual delivery line items are needed in the future, they should be
 *   added as a separate section or dedicated delivery export without modifying
 *   the aggregate summary structure or RFC 4180 quoting conventions.
 *
 * This test suite verifies:
 *   1. Correct aggregate section headings and headers.
 *   2. Exactly one performance summary row per driver.
 *   3. TOTALS row and PERCENTAGE row calculations.
 *   4. Departure time, arrival time, area coverage, and vehicle breakdowns.
 *   5. RFC 4180 compliance: escaping commas and double quotes.
 *   6. Aggregate contract: no individual delivery reference rows appear.
 */
