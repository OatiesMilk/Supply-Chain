test('DEF-019: RFC 4180 - cell containing commas and quotes is quoted correctly', () => {
  const csv = buildDriverReportCSV(mockDeliveries, mockDrivers, mockStats, 'OCTOBER', 2026, 'Logistics Officer', 'Logistics');
  // In the raw CSV string:
  // 1. Vehicle plates cell contains comma: "ABC-1234, XYZ-5678"
  assert.ok(csv.includes('"ABC-1234, XYZ-5678"'), 'Cell with comma must be quoted');
  // 2. Remarks cell contains double quote: "special" -> escaped as ""special""
  assert.ok(csv.includes('""special""'), 'Double quotes must be escaped as ""');
});

test('DEF-019: CSV contains NO individual delivery reference rows (aggregate-only contract confirmed)', () => {
  const csv = buildDriverReportCSV(mockDeliveries, mockDrivers, mockStats, 'OCTOBER', 2026, 'Logistics Officer', 'Logistics');
  const rows = parseCSVRows(csv);
  for (const row of rows) {
    for (const cell of row) {
      assert.notEqual(cell, 'UAT-OCT-DEL-01', 'Individual delivery reference must not appear in aggregate CSV');
      assert.notEqual(cell, 'UAT-OCT-DEL-02', 'Individual delivery reference must not appear in aggregate CSV');
    }
  }
});